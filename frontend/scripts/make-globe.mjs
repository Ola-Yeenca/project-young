const rad = (d) => (d * Math.PI) / 180;
const inside = (pt, poly) => {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i],
      [xj, yj] = poly[j];
    if (yi > pt[1] !== yj > pt[1] && pt[0] < ((xj - xi) * (pt[1] - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};
const land = (pt) => LAND.some((p) => inside(pt, p)) && !WATER.some((p) => inside(pt, p));
const project = (lon, lat) => {
  const p = rad(lat),
    p0 = rad(VIEW.lat),
    dl = rad(lon - VIEW.lon);
  const c = Math.acos(Math.sin(p0) * Math.sin(p) + Math.cos(p0) * Math.cos(p) * Math.cos(dl));
  const x = VIEW.cx + R * Math.cos(p) * Math.sin(dl),
    y = VIEW.cy - R * (Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(dl));
  return { x, y, deg: (c * 180) / Math.PI };
};
const f = (n) => (Math.round(n * 10) / 10).toString();

const inner = [],
  outer = [];
for (let lat = -70, row = 0; lat <= 78; lat += STEP, row++) {
  const dlon = STEP / Math.cos(rad(lat));
  for (let lon = -80 + (row % 2) * (dlon / 2); lon <= 90; lon += dlon) {
    const q = project(lon, lat);
    if (q.deg > VIEW.cap - 1.5 || !land([lon, lat])) continue;
    (q.deg < VIEW.cap - 12 ? inner : outer).push(`M${f(q.x)} ${f(q.y)}h0`);
  }
}

const grid = [];
const line = (pts) => {
  let seg = [];
  for (const [lon, lat] of pts) {
    const q = project(lon, lat);
    if (q.deg <= VIEW.cap) seg.push(`${f(q.x)} ${f(q.y)}`);
    else if (seg.length) {
      grid.push("M" + seg.join("L"));
      seg = [];
    }
  }
  if (seg.length > 1) grid.push("M" + seg.join("L"));
};
for (const lat of [-30, 0, 30, 60]) line(Array.from({ length: 181 }, (_, i) => [-90 + i, lat]));
for (const lon of [-30, 0, 30, 60]) line(Array.from({ length: 171 }, (_, i) => [lon, -85 + i]));

